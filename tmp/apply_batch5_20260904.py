import os, io
VAULT = r"D:/The Memory/The Memory"
CH, FA = [], []
def rep(rel, old, new, expect=1):
    p = os.path.join(VAULT, rel)
    if not os.path.exists(p): FA.append((rel, old[:24], "NO_FILE")); return
    t = io.open(p, encoding="utf-8").read()
    n = t.count(old)
    if n != expect: FA.append((rel, old[:24], f"count={n}")); return
    io.open(p, "w", encoding="utf-8").write(t.replace(old, new)); CH.append(rel)
def insert_after_fm(rel, block):
    p = os.path.join(VAULT, rel)
    t = io.open(p, encoding="utf-8").read()
    if "2026-09-04" in t[:600] and "销账" in block[:80] and "已销账" in t[:1200]:
        pass
    lines = t.split("\n")
    if lines[0].strip() == "---":
        end = next(i for i in range(1, len(lines)) if lines[i].strip() == "---")
        lines.insert(end + 1, "\n" + block.rstrip("\n"))
        io.open(p, "w", encoding="utf-8").write("\n".join(lines))
    else:
        io.open(p, "w", encoding="utf-8").write(block + "\n" + t)
    CH.append(rel + " [insert]")

